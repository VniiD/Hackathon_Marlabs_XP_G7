-- Patrimônio total (mesma conta do mock.ts: custódia + saldo externo +
-- posições externas).
CREATE VIEW v_client_net_worth AS
SELECT c.user_id AS client_id,
       COALESCE((SELECT sum(h.market_value) FROM holdings h WHERE h.client_id = c.user_id), 0)
     + COALESCE((SELECT sum(e.balance) FROM external_accounts e WHERE e.client_id = c.user_id), 0)
       AS total_net_worth
FROM client_profiles c;

-- Alocação por classe (diversificação RF03 / gatilho PROFILE_MISMATCH).
CREATE VIEW v_client_allocation AS
SELECT h.client_id,
       h.asset_class,
       sum(h.market_value) AS value,
       round(100 * sum(h.market_value) / NULLIF(sum(sum(h.market_value)) OVER (PARTITION BY h.client_id), 0), 2)
           AS pct
FROM holdings h
GROUP BY h.client_id, h.asset_class;

-- Sinais por cliente para o DailyAdvisorEngine (tudo menos a variação de
-- preço do dia, que vem das cotações no Redis).
CREATE VIEW v_client_signals AS
SELECT c.user_id                                   AS client_id,
       c.advisor_id,
       u.name,
       c.risk_profile,
       c.favorite_team,
       current_date - COALESCE(lc.last_contact, c.created_at)::date
                                                   AS days_since_last_contact,
       next_occurrence(c.birth_date) - current_date AS days_to_birthday,
       fd.label                                    AS next_family_date_label,
       fd.days                                     AS days_to_family_date,
       COALESCE(pr.open_requests, 0)               AS open_requests,
       mt.ticker                                   AS next_maturity_ticker,
       mt.days                                     AS days_to_maturity,
       nm.next_meeting_at,
       nw.total_net_worth
FROM client_profiles c
JOIN users u ON u.id = c.user_id
LEFT JOIN LATERAL (
    SELECT max(occurred_at) AS last_contact FROM contact_log WHERE client_id = c.user_id
) lc ON true
LEFT JOIN LATERAL (
    SELECT f.label,
           CASE WHEN f.recurring THEN next_occurrence(f.event_date) ELSE f.event_date END - current_date AS days
    FROM family_dates f
    WHERE f.client_id = c.user_id
      AND (f.recurring OR f.event_date >= current_date)
    ORDER BY 2
    LIMIT 1
) fd ON true
LEFT JOIN LATERAL (
    SELECT count(*) AS open_requests FROM portfolio_requests
    WHERE client_id = c.user_id AND status IN ('PENDING', 'IN_PROGRESS')
) pr ON true
LEFT JOIN LATERAL (
    SELECT h.ticker, h.maturity_date - current_date AS days
    FROM holdings h
    WHERE h.client_id = c.user_id AND h.maturity_date >= current_date
    ORDER BY h.maturity_date
    LIMIT 1
) mt ON true
LEFT JOIN LATERAL (
    SELECT min(starts_at) AS next_meeting_at FROM meetings
    WHERE client_id = c.user_id AND starts_at >= now() AND status IN ('PENDING', 'CONFIRMED')
) nm ON true
JOIN v_client_net_worth nw ON nw.client_id = c.user_id;