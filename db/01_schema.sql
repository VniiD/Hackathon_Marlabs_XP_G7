-- Janelas semanais de atendimento (RF05). find_free_slots = janelas - reuniões.
CREATE TABLE advisor_availability (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advisor_id  BIGINT   NOT NULL REFERENCES advisor_profiles (user_id) ON DELETE CASCADE,
    weekday     SMALLINT NOT NULL CHECK (weekday BETWEEN 1 AND 7),   -- ISO: 1 = segunda
    start_time  TIME     NOT NULL,
    end_time    TIME     NOT NULL,
    CHECK (end_time > start_time)
);
CREATE INDEX advisor_availability_idx ON advisor_availability (advisor_id, weekday);

CREATE TABLE meetings (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advisor_id   BIGINT      NOT NULL REFERENCES advisor_profiles (user_id),
    client_id    BIGINT      NOT NULL REFERENCES client_profiles (user_id) ON DELETE CASCADE,
    starts_at    TIMESTAMPTZ NOT NULL,                  -- TimeSlot.start
    ends_at      TIMESTAMPTZ NOT NULL,                  -- TimeSlot.end
    topic        TEXT        NOT NULL DEFAULT '',
    status       TEXT        NOT NULL DEFAULT 'PENDING'
                 CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'DONE')),
    created_via  TEXT        NOT NULL DEFAULT 'APP' CHECK (created_via IN ('APP', 'CHAT', 'ADVISOR')),
    -- Quem pediu a reunião; só a outra parte pode confirmar (PENDING -> CONFIRMED).
    initiated_by TEXT        NOT NULL DEFAULT 'CLIENT' CHECK (initiated_by IN ('CLIENT', 'ADVISOR')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (ends_at > starts_at),
    -- O banco recusa duas reuniões sobrepostas para o mesmo assessor.
    CONSTRAINT meetings_no_overlap EXCLUDE USING gist (
        advisor_id WITH =,
        tstzrange(starts_at, ends_at) WITH &&
    ) WHERE (status <> 'CANCELLED')
);
CREATE INDEX meetings_client_idx ON meetings (client_id, starts_at);


