CREATE EXTENSION IF NOT EXISTS btree_gist;   -- usado no EXCLUDE de meetings

-- Atualiza updated_at automaticamente em qualquer UPDATE.
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

-- Próxima ocorrência de uma data anual (aniversários). 29/02 vira 28/02 em
-- anos não bissextos.
CREATE OR REPLACE FUNCTION next_occurrence(d date, ref date DEFAULT current_date)
RETURNS date
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE
        WHEN this_year >= ref THEN this_year
        ELSE (d + make_interval(years => EXTRACT(YEAR FROM ref)::int - EXTRACT(YEAR FROM d)::int + 1))::date
    END
    FROM (SELECT (d + make_interval(years => EXTRACT(YEAR FROM ref)::int - EXTRACT(YEAR FROM d)::int))::date AS this_year) s;
$$;


-- =============================================================================
-- accounts — usuários, perfil do cliente, contexto pessoal, CRM
-- =============================================================================

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           TEXT        NOT NULL,
    email          TEXT        NOT NULL,
    password_hash  TEXT,                       -- NULL = conta criada pelo assessor, sem senha ainda
    role           TEXT        NOT NULL CHECK (role IN ('ADVISOR', 'CLIENT')),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_uq ON users (lower(email));
CREATE TRIGGER users_updated_at BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- FK para cá (e não para users) garante que advisor_id aponta para um assessor.
CREATE TABLE advisor_profiles (
    user_id   BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    crm_code  TEXT UNIQUE,                     -- código do assessor na XP
    timezone  TEXT NOT NULL DEFAULT 'America/Sao_Paulo'
);

CREATE TABLE client_profiles (
    user_id        BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,   -- = client_id
    advisor_id     BIGINT      NOT NULL REFERENCES advisor_profiles (user_id),
    risk_profile   TEXT        NOT NULL CHECK (risk_profile IN ('CONSERVADOR', 'MODERADO', 'ARROJADO')),
    birth_date     DATE,                                        -- gatilho BIRTHDAY
    -- PersonalContext
    favorite_team  TEXT,
    hobbies        TEXT[]      NOT NULL DEFAULT '{}',
    notes          TEXT,                                        -- observações livres do assessor
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX client_profiles_advisor_idx ON client_profiles (advisor_id);
CREATE TRIGGER client_profiles_updated_at BEFORE UPDATE ON client_profiles
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- PersonalContext.family_dates — gatilho FAMILY_DATE
CREATE TABLE family_dates (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id   BIGINT  NOT NULL REFERENCES client_profiles (user_id) ON DELETE CASCADE,
    label       TEXT    NOT NULL,                -- "Aniversário da filha"
    event_date  DATE    NOT NULL,
    recurring   BOOLEAN NOT NULL DEFAULT true    -- repete todo ano?
);
CREATE INDEX family_dates_client_idx ON family_dates (client_id);

-- CRM: cada contato do assessor com o cliente — gatilho INACTIVITY (RF09)
CREATE TABLE contact_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id    BIGINT      NOT NULL REFERENCES client_profiles (user_id) ON DELETE CASCADE,
    advisor_id   BIGINT      NOT NULL REFERENCES advisor_profiles (user_id),
    channel      TEXT        NOT NULL CHECK (channel IN ('CALL', 'WHATSAPP', 'EMAIL', 'MEETING', 'OTHER')),
    summary      TEXT,
    occurred_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX contact_log_client_idx ON contact_log (client_id, occurred_at DESC);


-- =============================================================================
-- portfolio — Open Finance, contas externas, posições, pedidos do cliente
-- =============================================================================

-- Não guardar access/refresh tokens aqui em texto puro: ficam no Redis com TTL
-- ou cifrados. Esta tabela só rastreia o consentimento (LGPD/Open Finance).
CREATE TABLE open_finance_consents (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id            BIGINT      NOT NULL REFERENCES client_profiles (user_id) ON DELETE CASCADE,
    institution          TEXT        NOT NULL,
    external_consent_id  TEXT,                     -- id do consentimento na instituição
    status               TEXT        NOT NULL DEFAULT 'PENDING'
                         CHECK (status IN ('PENDING', 'ACTIVE', 'REVOKED', 'EXPIRED')),
    permissions          TEXT[]      NOT NULL DEFAULT '{}',
    granted_at           TIMESTAMPTZ,
    expires_at           TIMESTAMPTZ,
    revoked_at           TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- No máximo um consentimento ativo por cliente/instituição.
CREATE UNIQUE INDEX consents_active_uq ON open_finance_consents (client_id, institution)
    WHERE status = 'ACTIVE';

-- ExternalAccount (portfolio/models.py). Some junto com o consentimento.
ALTER TABLE open_finance_consents ADD UNIQUE (id, client_id);   -- alvo da FK composta abaixo

CREATE TABLE external_accounts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consent_id   BIGINT        NOT NULL,
    client_id    BIGINT        NOT NULL,
    institution  TEXT          NOT NULL,                   -- copiado do consentimento
    account_id   TEXT          NOT NULL,                   -- id da conta na instituição
    balance      NUMERIC(18,2) NOT NULL DEFAULT 0,
    synced_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    UNIQUE (client_id, institution, account_id),
    UNIQUE (id, client_id),
    -- FK composta: a conta pertence ao mesmo cliente do consentimento.
    FOREIGN KEY (consent_id, client_id)
        REFERENCES open_finance_consents (id, client_id) ON DELETE CASCADE
);

-- Holding (portfolio/models.py).
--   external_account_id NULL  -> custódia XP (institution = "INTERNAL")
--   external_account_id = X   -> posição em outra instituição via Open Finance
CREATE TABLE holdings (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id            BIGINT        NOT NULL REFERENCES client_profiles (user_id) ON DELETE CASCADE,
    external_account_id  BIGINT,
    ticker               TEXT          NOT NULL,
    asset_class          TEXT          NOT NULL
                         CHECK (asset_class IN ('RENDA_FIXA', 'ACOES', 'FUNDOS', 'CRIPTO', 'OUTROS')),
    quantity             NUMERIC(24,8) NOT NULL CHECK (quantity >= 0),     -- 8 casas p/ cripto
    average_price        NUMERIC(18,6),                                    -- p/ rentabilidade (RF04)
    market_value         NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (market_value >= 0),
    maturity_date        DATE,                                             -- vencimento (renda fixa)
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    UNIQUE NULLS NOT DISTINCT (client_id, external_account_id, ticker),
    -- posição externa só pode estar numa conta do próprio cliente
    FOREIGN KEY (external_account_id, client_id)
        REFERENCES external_accounts (id, client_id) ON DELETE CASCADE
);
CREATE INDEX holdings_client_idx ON holdings (client_id);
CREATE INDEX holdings_ticker_idx ON holdings (ticker);
CREATE TRIGGER holdings_updated_at BEFORE UPDATE ON holdings
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Pedidos de alteração de carteira (RF06). O tool update_portfolio do
-- Gemini grava aqui; o painel do assessor lê os pendentes.
CREATE TABLE portfolio_requests (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id        BIGINT      NOT NULL REFERENCES client_profiles (user_id) ON DELETE CASCADE,
    request_type     TEXT        NOT NULL
                     CHECK (request_type IN ('APORTE', 'RESGATE', 'REBALANCEAMENTO', 'COMPRA', 'VENDA', 'OUTRO')),
    details          JSONB       NOT NULL DEFAULT '{}',    -- {"ticker": "PETR4", "quantity": 50}
    status           TEXT        NOT NULL DEFAULT 'PENDING'
                     CHECK (status IN ('PENDING', 'IN_PROGRESS', 'DONE', 'REJECTED')),
    source           TEXT        NOT NULL DEFAULT 'APP' CHECK (source IN ('APP', 'CHAT')),
    chat_message_id  BIGINT,                               -- FK adicionada depois de chat_messages
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at      TIMESTAMPTZ
);
CREATE INDEX portfolio_requests_open_idx ON portfolio_requests (client_id)
    WHERE status IN ('PENDING', 'IN_PROGRESS');


